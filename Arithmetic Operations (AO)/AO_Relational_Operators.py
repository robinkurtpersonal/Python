print("AO_Relational_Operators")


#greater than >
if 10 > 5:
    print("10 > 5")

#less than <
if 20 < 30:
    print("20 < 30")
#equal to ==
if 10 == 10:
    print("10 == 10")

#not equal to !=
if 10 != 0:
    print("10 != 0")
    
#greater than or equal to >=
if 20 >= 10:
    print("20 >= 10")
#less than or equal to <=

if 10 <= 20:
    print("10 <= 20")
    
