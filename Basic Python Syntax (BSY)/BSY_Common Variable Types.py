#Common Variable Types


#string == str
string = "Robin Kurt"
print(string)

#integer == int
integer = 10
print(integer)

#floatingpoint == float
floatingpoint = 1.5
print(floatingpoint)

#boolean == bool
boolean = True
print(boolean)


#check the types
#format: <class 'type'>
print(type(string))
print(type(integer))
print(type(floatingpoint))
print(type(boolean))
