#Python Comparison Operators
#usually done for conditions
#equal to ==
if 1 == 1:
    print("1 is equal to 1")
    
#not equal to != 
if 1 != 0:
    print("1 is not equal to zero")

#greater than >
if 60 > 50:
    print("50 greater than 60")

#less than <
if 50 < 60:
    print("50 is less than 60")

#greater than or equal to >=
if 50 >= 50:
    print("yes")

if 50 >= 40:
    print("yes")
#less than or equal to <=
if 50 <= 50:
    print("yes")

if 40 <= 50:
    print("yes")

